// Creates prisma/migrations/0001_init from schema.prisma, for projects that don't have migration files yet.
// Needed for production deploys (`npm run db:deploy`). Skip it if you already have a prisma/migrations folder.
import fs from "node:fs";
import { execSync } from "node:child_process";

const root = "prisma/migrations";
if (fs.existsSync(root) && fs.readdirSync(root).some((f) => f !== "migration_lock.toml")) {
  console.log("Migrations already exist. Nothing to do.");
  process.exit(0);
}
const dir = `${root}/0001_init`;
fs.mkdirSync(dir, { recursive: true });
const sql = execSync("npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script", { encoding: "utf8" });
fs.writeFileSync(`${dir}/migration.sql`, sql);
fs.writeFileSync(`${root}/migration_lock.toml`, '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
console.log(`Created ${dir}. Commit the prisma/migrations folder.`);
